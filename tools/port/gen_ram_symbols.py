#!/usr/bin/env python3
"""Generate port/game/ram_symbols.c from linker.ld (mf-android).

The Fusion decomp defines almost every IWRAM variable (and a few EWRAM ones)
only in linker.ld, by address. The native build keeps that exact layout: the
GBA's EWRAM and IWRAM are two host buffers (gPortEwram, gPortIwram), and each
linker.ld symbol becomes an ELF symbol at its offset inside them. Code that
treats neighbouring variables as one block (DMA clears, overflows) then
behaves as on the GBA.

Usage: gen_ram_symbols.py linker.ld > port/game/ram_symbols.c
"""
import re
import sys

SYM = re.compile(r'\.\s*=\s*(0x[0-9a-fA-F]+)\s*;\s*([A-Za-z_]\w*)\s*=\s*\.\s*;')
SECTION = re.compile(r'^\s*(ewram|iwram)\s*\(NOLOAD\)')
SIZES = {"ewram": 256 * 0x400, "iwram": 32 * 0x400}
BUFFERS = {"ewram": "gPortEwram", "iwram": "gPortIwram"}


def main():
    syms = {"ewram": [], "iwram": []}
    region = None
    for line in open(sys.argv[1]):
        m = SECTION.match(line)
        if m:
            region = m.group(1)
            continue
        if region and line.strip().startswith("}"):
            region = None
            continue
        if region:
            m = SYM.search(line)
            if m:
                syms[region].append((int(m.group(1), 16), m.group(2)))

    out = [
        "// Generated by tools/port/gen_ram_symbols.py from linker.ld: do not edit.",
        "//",
        "// The GBA's EWRAM and IWRAM as two host buffers, with every variable that",
        "// linker.ld places by address defined at the same offset inside them.",
        "",
        "__asm__(",
        '    "\\t.section .bss.mf_gba_ram,\\"aw\\",%nobits\\n"',
    ]
    for region in ("ewram", "iwram"):
        buf = BUFFERS[region]
        out += [
            '    "\\t.balign 16\\n"',
            f'    "\\t.globl {buf}\\n"',
            f'    "\\t.type {buf}, %object\\n"',
            f'    "\\t.size {buf}, 0x{SIZES[region]:x}\\n"',
            f'    "{buf}:\\n"',
            f'    "\\t.zero 0x{SIZES[region]:x}\\n"',
        ]
        for off, name in syms[region]:
            out += [
                f'    "\\t.globl {name}\\n"',
                f'    "\\t.type {name}, %object\\n"',
                f'    "\\t.set {name}, {buf} + 0x{off:x}\\n"',
            ]
    out += ['    "\\t.previous\\n"', ");", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
